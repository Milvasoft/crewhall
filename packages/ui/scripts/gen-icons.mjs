// Generates src/icons/paths.ts from the design kit icon sprite (docs/Crewhall tasarımı/_kit/icons.html).
// Only the product icon set (i-*) and the Crewhall mark are taken; tenant logos are data, never code.
// Usage: node packages/ui/scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const sprite = readFileSync(join(here, '../../../docs/Crewhall tasarımı/_kit/icons.html'), 'utf8');
const re = /<symbol id="i-([A-Za-z0-9]+)" viewBox="0 0 24 24"[^>]*>([\s\S]*?)<\/symbol>/g;
const icons = {};
for (const m of sprite.matchAll(re)) icons[m[1]] = m[2].replace(/\s+/g, ' ').trim();
const names = Object.keys(icons).sort();
const body = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(icons[n])},`).join('\n');
writeFileSync(
  join(here, '../src/icons/paths.ts'),
  `// Generated by scripts/gen-icons.mjs from the design kit. Do not edit by hand.\n` +
    `// 24x24 line icons, stroke 1.8, currentColor.\nexport const ICON_PATHS = {\n${body}\n} as const;\n\n` +
    `export type IconName = keyof typeof ICON_PATHS;\n`,
);
console.log(`${names.length} icons`);
