/** Pick a supported locale from an Accept-Language style list. */
export function resolveLocale(
  candidates: readonly string[] | string | null | undefined,
): AppLocale {
  const list = typeof candidates === 'string' ? candidates.split(',') : (candidates ?? []);
  for (const c of list) {
    const base = c.trim().slice(0, 2).toLowerCase();
    if ((LOCALES as readonly string[]).includes(base)) return base as AppLocale;
  }
  return DEFAULT_LOCALE;
}
