import type { ImportVersion } from '../bundle';
import { arr, obj, readDocusaurusConfig, str, type JsObject } from './config';
import type { ParseContext } from './context';

/** One Docusaurus docs version and where its files are. */
export interface VersionSource extends ImportVersion {
  /** Docusaurus version name: `current` or the versions.json entry. */
  docusaurusName: string;
  /** Docs root of the default locale, e.g. `docs` or `versioned_docs/version-1.0.0`. */
  contentDir: string;
  /** Folder name below `i18n/<locale>/docusaurus-plugin-content-docs/`. */
  localizedDirName: string;
  /** Sidebar ids (first one names the `sidebar.<id>.category.*` translation keys). */
  sidebarIds: string[];
  /** False when the sidebar is not a single autogenerated one (order is then approximated). */
  autogenerated: boolean;
}

export const VERSION_PATTERN = /^\d+(\.\d+){0,3}([-.][0-9A-Za-z.]+)?$/;

/**
 * Docusaurus versions → portal versions: `lastVersion` is the current release; with
 * `lastVersion: 'current'` the current docs take their name from `versions.current.path`
 * (or label). The docs folder of an unreleased `current` becomes `next`; otherwise an empty
 * `next` entry is added for the importer to fill from the current release.
 */
export function readVersions(
  ctx: ParseContext,
  docsOptions: JsObject,
): { versions: VersionSource[]; currentVersion: string } {
  const docsPath = str(docsOptions.path) ?? 'docs';
  const raw = ctx.readJson('versions.json');
  const archivedNames = Array.isArray(raw)
    ? raw.filter((v): v is string => typeof v === 'string')
    : [];
  const versionsCfg = obj(docsOptions.versions);
  const lastVersion = str(docsOptions.lastVersion) ?? archivedNames[0] ?? 'current';
  const includeCurrent = docsOptions.includeCurrentVersion !== false;

  const versions: VersionSource[] = [];
  const sidebarOf = (file: string) => readSidebars(ctx, file);

  const currentCfg = obj(versionsCfg.current);
  let currentVersion: string;
  if (lastVersion === 'current') {
    let name = str(currentCfg.path) ?? str(currentCfg.label);
    if (!name || !VERSION_PATTERN.test(name)) {
      const fallback = '1.0.0';
      ctx.report({
        type: 'setting',
        source: 'docusaurus.config.js › docs.versions.current',
        action: `Güncel dokümanların versiyon numarası yok; ${fallback} olarak alındı. /docs/… adresleri /docs/${fallback}/… oldu, yönlendirme gerekir`,
        target: null,
      });
      name = fallback;
    }
    currentVersion = name;
    if (includeCurrent) {
      versions.push({
        name,
        label: str(currentCfg.label) ?? name,
        status: 'current',
        showInPicker: true,
        docusaurusName: 'current',
        contentDir: docsPath,
        localizedDirName: 'current',
        ...sidebarOf(str(docsOptions.sidebarPath) ?? 'sidebars.js'),
      });
    }
  } else {
    currentVersion = lastVersion;
  }

  for (const v of archivedNames) {
    const cfg = obj(versionsCfg[v]);
    versions.push({
      name: v,
      label: str(cfg.label) ?? v,
      status: v === lastVersion ? 'current' : 'archived',
      showInPicker: true,
      docusaurusName: v,
      contentDir: `versioned_docs/version-${v}`,
      localizedDirName: `version-${v}`,
      ...sidebarOf(`versioned_sidebars/version-${v}-sidebars.json`),
    });
  }

  const nextFromCurrent = lastVersion !== 'current' && includeCurrent;
  versions.push({
    name: 'next',
    label: nextFromCurrent ? (str(currentCfg.label) ?? 'Next') : 'Next',
    status: 'next',
    showInPicker: false,
    docusaurusName: nextFromCurrent ? 'current' : '',
    contentDir: nextFromCurrent ? docsPath : '',
    localizedDirName: nextFromCurrent ? 'current' : '',
    ...(nextFromCurrent
      ? sidebarOf(str(docsOptions.sidebarPath) ?? 'sidebars.js')
      : { sidebarIds: [], autogenerated: true }),
  });

  return { versions, currentVersion };
}

function readSidebars(
  ctx: ParseContext,
  file: string,
): { sidebarIds: string[]; autogenerated: boolean } {
  if (!ctx.isFile(file)) return { sidebarIds: ['docsSidebar'], autogenerated: true };
  let sidebars: JsObject;
  if (file.endsWith('.json')) {
    const data = ctx.readJson(file);
    sidebars = data && typeof data === 'object' && !Array.isArray(data) ? (data as JsObject) : {};
  } else {
    sidebars = readDocusaurusConfig(ctx.read(file)).config;
  }
  const ids = Object.keys(sidebars);
  const autogenerated =
    ids.length > 0 &&
    ids.every((id) => {
      const items = arr(sidebars[id]);
      const first = obj(items[0]);
      return items.length === 1 && first.type === 'autogenerated';
    });
  if (!autogenerated) {
    ctx.report({
      type: 'unsupported',
      source: file,
      action: 'Elle tanımlanmış sidebar; kategori ve sıra klasör yapısından alındı, kontrol et',
      target: null,
    });
  }
  return { sidebarIds: ids.length ? ids : ['docsSidebar'], autogenerated };
}
